#!/usr/bin/env python3
"""Generate the portable renderer's 1-bit subset; Pillow + fontTools required."""
from pathlib import Path
import re
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont
from fontTools import subset

ROOT = Path(__file__).resolve().parents[1]
source = ROOT / 'managed_components/lvgl__lvgl/tests/src/test_files/fonts/noto/NotoSansSC-Regular.ttf'
target = ROOT / 'assets/fonts/Wreck.ttf'
texts = (ROOT / 'main/wreck_render.c').read_text()
chars = sorted(set(chr(i) for i in range(32,127)) | set(re.findall(r'[\u3400-\u9fff]', texts)))
font = TTFont(source)
cmap = font.getBestCmap()
assert all(ord(c) in cmap for c in chars), 'Source font lacks requested glyphs'
options = subset.Options()
sub = subset.Subsetter(options=options)
sub.populate(text=''.join(chars))
sub.subset(font)
font.save(target)
bits = bytearray()
tables = []
for size in (12,16,24):
    face = ImageFont.truetype(str(target),size)
    entries=[]
    boxes={c:face.getbbox(c,anchor='ls') for c in chars}
    baseline=-min(box[1] for box in boxes.values())
    h=baseline+max(box[3] for box in boxes.values())
    for c in chars:
        left,top,right,bottom=boxes[c]
        inset=-min(0,left)
        w=max(1,round(face.getlength(c))+1,right+inset+1)
        assert 0<=baseline+top<=baseline+bottom<=h
        im=Image.new('L',(w,h));d=ImageDraw.Draw(im)
        d.text((inset,baseline),c,font=face,fill=255,anchor='ls',stroke_width=0)
        offset=len(bits);b=bytearray((w*h+7)//8)
        for y in range(h):
            for x in range(w):
                if im.getpixel((x,y))>=90:b[(y*w+x)//8]|=1<<((y*w+x)%8)
        bits.extend(b);entries.append((ord(c),w,h,offset))
    tables.append(entries)
out=['/* Generated by tools/wreck_font.py; Noto Sans SC, SIL OFL 1.1. */','#pragma once','#include <stdint.h>',
     f'#define WRECK_GLYPH_COUNT {len(chars)}','typedef struct {uint32_t cp;uint8_t width,height;uint32_t offset;} wreck_glyph_t;',
     'static const uint8_t wreck_font_bits[]={']
for i in range(0,len(bits),24):out.append(','.join(map(str,bits[i:i+24]))+',')
out.append('};\nstatic const wreck_glyph_t wreck_glyphs[3][WRECK_GLYPH_COUNT]={')
for entries in tables:
    out.append('{'+','.join('{%d,%d,%d,%d}'%e for e in entries)+'},')
out.append('};\n')
(ROOT / 'assets/fonts/wreck_font.h').write_text('\n'.join(out))
print(f'Font coverage PASS: {len(chars)} codepoints at 12/16/24px, {len(bits)} bitmap bytes')
